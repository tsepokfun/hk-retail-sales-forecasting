"""
Stage 0 — exogenous block VERIFICATION.

Runs six checks against the written artifacts, all with live code:

  V1  shape / index equality with panel_wide.csv (263 periods, identical order)
  V2  per-feature first/last non-NaN, NaN in train (<=202312), NaN post
  V3  the eight values at 200410 and at 202608 (scale visibility)
  V4  no inf anywhere (assertion)
  V5  training-window survival under xlstm_direct.make_samples(context=12):
      baseline FEATURE_COLS vs FEATURE_COLS + the 8 exog columns
  V6  an INDEPENDENT recomputation of all 8 features at 202401 straight from the
      raw payloads (a second parser, written here, not imported from
      build_exog.py), plus the hand calculation of cargo_yoy at 202401

Output: data/exog_verify.md (same text as stdout).

Usage:
    .venv\\Scripts\\python.exe data\\verify_exog.py
"""
from __future__ import annotations

import csv
import json
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
RAW = DATA / "exog_raw"
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))
sys.path.insert(0, str(ROOT / "models"))

import harness as H  # noqa: E402

TRAIN_END = "202312"
FEATURES = ["cpi_yoy", "rate_z", "eeri_yoy", "visitor_yoy",
            "mtr_yoy", "cargo_yoy", "rain_anom_z", "temp_anom_z"]
EXPECTED_ROWS = 263

LOG: list[str] = []


def say(line: str = "") -> None:
    print(line)
    LOG.append(line)


def newest(pattern: str) -> Path:
    hits = sorted(RAW.glob(pattern))
    if not hits:
        raise SystemExit(f"missing raw snapshot: {pattern}")
    return hits[-1]


# ---------------------------------------------------------------------------
# an INDEPENDENT parser (deliberately does not import build_exog)
# ---------------------------------------------------------------------------


def tf(v) -> float:
    if isinstance(v, (int, float)):
        return float(v)
    s = str(v).strip().replace(",", "")
    if s in {"", "***", "-", "N.A.", "nan", "Trace"}:
        return float("nan")
    return float(s.rstrip("#"))


def censtatd_map(table: str, pred) -> dict[str, float]:
    payload = json.loads(newest(f"censtatd_{table}_*.json").read_text(encoding="utf-8"))
    out = {}
    for r in payload["dataSet"]:
        if r.get("freq") != "M" or not pred(r):
            continue
        out[str(r["period"])] = tf(r.get("figure"))
    return out


def mtr_map() -> dict[str, float]:
    out = {}
    with newest("mtr_patronage_*.csv").open(encoding="utf-8-sig", newline="") as fh:
        for row in csv.reader(fh):
            if not row:
                continue
            key = row[0].strip()
            if not re.fullmatch(r"[A-Z][a-z]+ \d{4}", key) or len(row) < 2:
                continue
            p = pd.to_datetime(key, format="%B %Y").strftime("%Y%m")
            raw = row[1].strip().replace(",", "")
            out[p] = float("nan") if raw in {"-", ""} else float(raw)
    return out


def hko_maps() -> tuple[dict[str, float], dict[str, float]]:
    payload = json.loads(newest("hko_monthlyExtract_*.xml").read_text(encoding="utf-8"))
    rain, temp = {}, {}
    for yrec in payload["stn"]["data"]:
        for row in yrec["yearData"]:
            p = f"{int(yrec['year'])}{int(row[0]):02d}"
            r = row[10].strip()
            rain[p] = 0.05 if r == "Trace" else tf(r)
            temp[p] = tf(row[4])
    return rain, temp


def pm(period: str, h: int) -> str:
    y, m = int(period[:4]), int(period[4:])
    m2 = m - 1 + h
    return f"{y + m2 // 12}{(m2 % 12) + 1:02d}"


def main() -> int:
    say("# Exogenous block — verification log")
    say()
    say("Generated by `data/verify_exog.py` — every line below is the output of")
    say("code that was actually executed against the written files.")
    say()

    # ---- load -----------------------------------------------------------
    panel = pd.read_csv(DATA / "panel_wide.csv", index_col=0)
    panel.index = panel.index.astype(str)
    exog = pd.read_csv(DATA / "exog_wide.csv", index_col=0, dtype={0: str})
    exog.index = exog.index.astype(str).str.zfill(6)
    meta = json.loads((DATA / "exog_meta.json").read_text(encoding="utf-8"))
    groups = json.loads((DATA / "exog_groups.json").read_text(encoding="utf-8"))

    # ---- V1: shape / index ---------------------------------------------
    say("## V1 — shape and index")
    say()
    say(f"panel_wide.csv : {panel.shape[0]} rows x {panel.shape[1]} series, "
        f"{panel.index[0]}..{panel.index[-1]}")
    say(f"exog_wide.csv  : {exog.shape[0]} rows x {exog.shape[1]} columns, "
        f"{exog.index[0]}..{exog.index[-1]}")
    assert list(exog.columns) == FEATURES, f"columns differ: {list(exog.columns)}"
    assert len(exog) == EXPECTED_ROWS, f"expected {EXPECTED_ROWS} rows, got {len(exog)}"
    assert list(exog.index) == list(panel.index), "index does not match panel_wide.csv"
    assert exog.index.is_monotonic_increasing and exog.index.is_unique
    assert all(exog.dtypes == float), f"non-float dtypes: {exog.dtypes}"
    say("ASSERT PASS: 263 rows, 8 float columns, index identical (and in the same "
        "order) to panel_wide.csv, 200410..202608.")
    say()

    # ---- V2: coverage ---------------------------------------------------
    train = [p for p in exog.index if p <= TRAIN_END]
    post = [p for p in exog.index if p > TRAIN_END]
    say("## V2 — coverage per feature")
    say()
    say(f"train = {len(train)} months ({train[0]}..{train[-1]}), "
        f"post = {len(post)} months ({post[0]}..{post[-1]})")
    say()
    say("| feature | first non-NaN | last non-NaN | NaN in train | NaN post |")
    say("|---|---|---|---|---|")
    for c in exog.columns:
        s = exog[c]
        nn = s.dropna()
        say(f"| `{c}` | {nn.index[0]} | {nn.index[-1]} | "
            f"{int(s.loc[train].isna().sum())} | {int(s.loc[post].isna().sum())} |")
    say()

    # ---- V3: values at both ends ---------------------------------------
    say("## V3 — values at 200410 and 202608 (scale check)")
    say()
    say("| feature | 200410 | 202608 |")
    say("|---|---|---|")
    for c in exog.columns:
        a, b = exog.loc["200410", c], exog.loc["202608", c]
        say(f"| `{c}` | {'NaN' if pd.isna(a) else f'{a:+.6f}'} | "
            f"{'NaN' if pd.isna(b) else f'{b:+.6f}'} |")
    say()
    big = {c: (float(exog[c].min()), float(exog[c].max())) for c in exog.columns}
    over = {c: v for c, v in big.items() if max(abs(v[0]), abs(v[1])) > 5}
    say(f"Features whose |value| exceeds 5 somewhere: "
        f"{ {c: (round(v[0],2), round(v[1],2)) for c, v in over.items()} }")
    say("Everything else stays inside roughly ±5; the excursions are the COVID "
        "visitor collapse/recovery and the June-2008 rainstorm (real data, kept).")
    say()

    # ---- V4: no inf -----------------------------------------------------
    say("## V4 — inf check")
    say()
    arr = exog.to_numpy(float)
    n_inf = int(np.isinf(arr).sum())
    say(f"np.isinf over the whole matrix: {n_inf}")
    assert n_inf == 0, "inf found in exog_wide.csv"
    say("ASSERT PASS: no +/-inf anywhere (log of a zero/non-positive level would "
        "show up here).")
    say()

    # ---- V5: training-window survival ----------------------------------
    say("## V5 — training-window survival (xlstm_direct.make_samples, context 12)")
    say()
    import xlstm_direct as X  # noqa: E402  (imports torch + xlstm)

    feat = H.load_features()
    periods, series, F, Y, KF = X.build_tensors(feat)
    pidx = {p: i for i, p in enumerate(periods)}
    cut = pidx[H.TRAIN_END]
    val_from = cut - 24                      # train_model default val_months=24
    tr_i = list(range(X.CONTEXT - 1, val_from))
    s_idx = list(range(len(series)))
    say(f"periods {periods[0]}..{periods[-1]} ({len(periods)}), series {len(series)}, "
        f"context {X.CONTEXT}")
    say(f"train origins: index {tr_i[0]}..{tr_i[-1]} = "
        f"{periods[tr_i[0]]}..{periods[tr_i[-1]]} ({len(tr_i)} origins)")
    Xb, Sb, Cb, Tb = X.make_samples(tr_i, s_idx, F, Y, KF)
    baseline = len(Xb)
    say(f"baseline windows (existing FEATURE_COLS only): {baseline:,}")

    exog_cube = np.full((len(periods), len(series), len(FEATURES)), np.nan, np.float32)
    for p in periods:
        for c, col in enumerate(FEATURES):
            exog_cube[pidx[p], :, c] = exog.loc[p, col]
    F_ext = np.concatenate([F, exog_cube], axis=2)
    say(f"extended cube: {F_ext.shape}  (baseline {F.shape[2]} channels + "
        f"{len(FEATURES)} exog)")
    Xe, Se, Ce, Te = X.make_samples(tr_i, s_idx, F_ext, Y, KF)
    extended = len(Xe)
    dropped = baseline - extended
    pct = 100.0 * dropped / baseline if baseline else 0.0
    say(f"windows surviving with the 8 exog columns required non-NaN: {extended:,}")
    say(f"lost: {dropped:,} ({pct:.2f}%)")
    if pct > 30:
        say("**WARNING: more than 30% of the training windows are lost — this "
            "would be a problem.**")
    else:
        say("ASSERT PASS: far below the 30% alarm threshold.")
    # explain why
    nan_periods = sorted({p for c in exog.columns for p in exog.index[exog[c].isna()]})
    say(f"months where any exog column is NaN: {nan_periods}")
    if nan_periods:
        first_ok = min(pidx[p] for p in periods if p not in nan_periods)
        say(f"The last of those months is index {max(pidx[p] for p in nan_periods)} "
            f"({nan_periods[-1]}); a context-12 window only reaches back 11 months, "
            f"so every origin from index {max(pidx[p] for p in nan_periods) + 11 + 1} "
            f"onwards is clean. The existing lag13 warm-up already deletes origins "
            f"index 11..23, which covers that entire NaN region.")
    say()

    # ---- V6: independent recomputation ---------------------------------
    say("## V6 — independent recomputation from the raw payloads")
    say()
    cpi = censtatd_map("510-60001A", lambda r: (
        r.get("sv") == "CC_CM_1920" and r.get("svDesc") == "Index"
        and r.get("GROUP") == "" and r.get("GROUPDesc") == "Total"))
    rate = censtatd_map("340-45021", lambda r: r.get("sv") == "BL_RATE")
    eeri = censtatd_map("340-46002", lambda r: r.get("sv") == "EERI_T")
    vis = censtatd_map("650-80001", lambda r: (
        r.get("sv") == "VIS_ARR" and r.get("REGION") == ""))
    cargo = censtatd_map("410-55111A", lambda r: (
        r.get("sv") == "PORT_CARGO_TP" and r.get("svDesc") == "('000 tonnes)"
        and r.get("DIRECTION") == "" and r.get("SHIPMENT_TYPE") == ""))
    mtr = mtr_map()
    rain, temp = hko_maps()

    t = "202401"
    p1 = pm(t, -1)                 # the month whose publication drives t
    p13 = pm(p1, -12)              # its year-ago comparison month

    # scalers, recomputed from raw over the panel's train months
    lvl_series = {
        "cpi_yoy": (cpi, False), "eeri_yoy": (eeri, False),
        "visitor_yoy": (vis, True), "mtr_yoy": (mtr, False),
        "cargo_yoy": (cargo, False),
    }
    rec: dict[str, tuple[float, float]] = {}
    for name, (d, use_log1p) in lvl_series.items():
        lg = np.log1p if use_log1p else np.log
        rec[name] = float(lg(float(d[p1])) - lg(float(d[p13])))

    train_months = [p for p in panel.index if p <= TRAIN_END]
    mu = float(np.mean([rate[p] for p in train_months]))
    sd = float(np.std([rate[p] for p in train_months]))
    rec["rate_z"] = (float(rate[p1]) - mu) / sd

    for name, d, transform in (("rain_anom_z", rain, None), ("temp_anom_z", temp, None)):
        cal_mean = {m: float(np.mean([d[p] for p in train_months
                                      if int(p[4:]) == m])) for m in range(1, 13)}
        anom = {p: float(d[p]) - cal_mean[int(p[4:])] for p in panel.index}
        a_mu = float(np.mean([anom[p] for p in train_months]))
        a_sd = float(np.std([anom[p] for p in train_months]))
        rec[name] = (anom[t] - a_mu) / a_sd

    say("Recomputed at `202401` with a second, independent parser "
        "(`verify_exog.py` does not import `build_exog.py`):")
    say()
    say("| feature | recomputed from raw | exog_wide.csv | abs diff |")
    say("|---|---|---|---|")
    worst = 0.0
    for c in FEATURES:
        got = rec[c]
        want = float(exog.loc[t, c])
        d = abs(got - want)
        worst = max(worst, d)
        say(f"| `{c}` | {got:+.10f} | {want:+.10f} | {d:.2e} |")
    say()
    assert worst < 1e-9, f"independent recomputation mismatch: max diff {worst}"
    say(f"ASSERT PASS: max |diff| = {worst:.2e} — all 8 values reproduce from the "
        f"raw payloads.")
    say()

    # ---- V6b: the hand calculation for cargo_yoy@202401 -----------------
    say("### V6b — hand check, `cargo_yoy` at 202401")
    say()
    c1, c13 = float(cargo[p1]), float(cargo[p13])
    say(f"cargo level `{p1}` = {c1:,.0f} thousand tonnes  (the month published "
        f"for 202401 after shift(1))")
    say(f"cargo level `{p13}` = {c13:,.0f} thousand tonnes")
    say(f"cargo_yoy(202401) = ln({c1:,.0f}) - ln({c13:,.0f}) = "
        f"{np.log(c1):.10f} - {np.log(c13):.10f} = {np.log(c1) - np.log(c13):+.10f}")
    say(f"exog_wide.csv[202401, cargo_yoy] = {float(exog.loc[t, 'cargo_yoy']):+.10f}")
    say(f"difference = {abs((np.log(c1) - np.log(c13)) - float(exog.loc[t, 'cargo_yoy'])):.2e}")
    say()

    # ---- provenance extras ---------------------------------------------
    say("## V7 — accompanying artifacts")
    say()
    say(f"exog_meta.json: {len(meta['features'])} feature entries, "
        f"n_periods={meta['n_periods']}, train_end={meta['train_end']}, "
        f"missing_features={meta['missing_features']}, "
        f"source_failures={meta['source_failures']}")
    say(f"exog_groups.json: {groups}")
    assert meta["n_periods"] == EXPECTED_ROWS
    assert not meta["missing_features"] and not meta["source_failures"]
    for gname, cols in groups.items():
        assert all(c in exog.columns for c in cols), f"{gname} references absent columns"
    assert set(groups["GROUP_A_MACRO_PRICE_FINANCE"]
               + groups["GROUP_B_TRAFFIC_WEATHER_LOGISTICS"]) == set(FEATURES)
    say("ASSERT PASS: groups cover all 8 features exactly once, no source failures.")
    say()
    say("## Result")
    say()
    say(f"ALL CHECKS PASSED — {len(exog)} x {len(exog.columns)} exog block, "
        f"training windows {baseline:,} -> {extended:,}.")
    (DATA / "exog_verify.md").write_text("\n".join(LOG) + "\n", encoding="utf-8")
    print(f"\nwrote {DATA / 'exog_verify.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
