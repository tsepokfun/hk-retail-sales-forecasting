"""
Stage 3 / step 2 — turn GovHK headlines into two monthly text representations.

OUTPUT  stage3/data/news_text_wide.csv   (263 rows x [period + 7 features])

REPRESENTATIONS
    text_scalar  (3 columns, "count + dictionary")
        news_log_count   log1p(number of headlines in the month)
        news_fin_share   share matching retail / consumer / tourism / price /
                         rate / voucher / epidemic vocabulary
        news_sent_net    (positive - negative) / (positive + negative) over a
                         small hand-written lexicon

    text_emb     (4 columns, "learned representation")
        news_pc1..4      mean of the month's title embeddings -> PCA(4)

CAUSALITY RULES (the whole point of this file)
    1. A month's features use ONLY headlines whose publication date falls in that
       month.  Nothing is read from a later month.
    2. `shift(0)`: month-t headlines are all published inside month t, so they are
       known at origin t.  This is the same treatment HKO weather got in Stage 1
       (see EXOG.md judgement call J8) and is NOT a look-ahead.
    3. Every fitted object -- PCA, TF-IDF vocabulary, z-score mu/sigma -- is fit
       on `period <= 202312` only.
    4. `news_prefix_test()` masks all headlines dated after a cut and re-derives
       the features; the in-window values must be identical.

COVERAGE GAP (measured, not assumed)
    The daily archive page is not machine-readable for part of 2005-2007 (the
    markup is generated by inline script and yields no anchors).  Months with
    zero headlines are recorded as NO COVERAGE (NaN), then imputed to the
    training-period mean, i.e. z = 0 -- "an average news month", which is the
    only defensible reading when the measurement is missing.  Never imputed to
    zero, which would falsely assert "no news happened".
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
TRAIN_END = "202312"
EMB_DIM = 4

FIN_RE = re.compile(
    r"retail|sales|consum|touris|visitor|inflation|price|econom|rate|tax|"
    r"voucher|epidemic|covid|market|trade|export|import|gdp|unemploy|"
    r"property|rent|shop|mall|spending|revenue|business|duty|tariff",
    re.I)

POS = ["rise", "rises", "rose", "up", "growth", "grow", "grows", "grew", "increase",
       "increases", "record", "surge", "surges", "boost", "boosts", "improve",
       "improves", "improved", "recovery", "recovers", "rebound", "rebounds",
       "strong", "stronger", "gain", "gains", "expand", "expands", "high",
       "higher", "welcome", "welcomes", "launch", "launches", "success",
       "successful", "approve", "approves", "approved", "support", "supports"]
NEG = ["fall", "falls", "fell", "down", "drop", "drops", "dropped", "decline",
       "declines", "declined", "decrease", "decreases", "slump", "slumps",
       "weak", "weaker", "loss", "losses", "cut", "cuts", "low", "lower",
       "concern", "concerns", "warning", "warns", "protest", "protests",
       "strike", "strikes", "accident", "injured", "death", "deaths", "fraud",
       "arrest", "arrests", "seized", "recall", "recalls", "deficit", "debt"]
POS_RE = re.compile(r"\b(" + "|".join(POS) + r")\b", re.I)
NEG_RE = re.compile(r"\b(" + "|".join(NEG) + r")\b", re.I)


def load_headlines() -> pd.DataFrame:
    f = DATA / "news_headlines.csv"
    if not f.exists():
        raise SystemExit(f"missing {f} -- run news_fetch.py first")
    d = pd.read_csv(f, dtype={"date": str, "month": str, "title": str})
    return d


def month_scalar(d: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for m, g in d.groupby("month"):
        titles = g["title"].astype(str).tolist()
        n = len(titles)
        fin = sum(1 for t in titles if FIN_RE.search(t))
        p = sum(len(POS_RE.findall(t)) for t in titles)
        q = sum(len(NEG_RE.findall(t)) for t in titles)
        rows.append({
            "month": m,
            "news_log_count": float(np.log1p(n)) if n else np.nan,
            "news_fin_share": fin / n if n else np.nan,
            "news_sent_net": (p - q) / (p + q) if (p + q) else np.nan,
        })
    return pd.DataFrame(rows).set_index("month")


def month_embeddings_st(d: pd.DataFrame):
    """mean of per-title sentence embeddings, then PCA on train months only"""
    from sentence_transformers import SentenceTransformer
    from sklearn.decomposition import PCA

    model = SentenceTransformer("sentence-transformers/all-MiniLM-L6-v2")
    months, vecs = [], []
    for m, g in d.groupby("month"):
        titles = g["title"].astype(str).tolist()
        if not titles:
            continue
        E = model.encode(titles, batch_size=64, show_progress_bar=False,
                         convert_to_numpy=True, normalize_embeddings=False)
        months.append(m)
        vecs.append(E.mean(axis=0))
    M = pd.DataFrame(np.vstack(vecs), index=months)
    M.index.name = "month"
    tr = M.index <= TRAIN_END
    pca = PCA(n_components=EMB_DIM, random_state=0).fit(M.loc[tr])
    Z = pca.transform(M)
    out = pd.DataFrame(Z, index=M.index,
                       columns=[f"news_pc{i+1}" for i in range(EMB_DIM)])
    info = {"encoder": "sentence-transformers/all-MiniLM-L6-v2",
            "pca_fit_months": int(tr.sum()),
            "explained_variance_ratio": [round(float(x), 4)
                                         for x in pca.explained_variance_ratio_]}
    return out, info


def month_embeddings_tfidf(d: pd.DataFrame):
    """fallback: TF-IDF over the month's concatenated titles, then SVD"""
    from sklearn.decomposition import TruncatedSVD
    from sklearn.feature_extraction.text import TfidfVectorizer

    docs, months = [], []
    for m, g in d.groupby("month"):
        titles = g["title"].astype(str).tolist()
        if not titles:
            continue
        months.append(m)
        docs.append(" . ".join(titles))
    vec = TfidfVectorizer(max_features=2000, stop_words="english",
                          lowercase=True, sublinear_tf=True)
    tr_mask = np.array([m <= TRAIN_END for m in months])
    vec.fit([d_ for d_, k in zip(docs, tr_mask) if k])          # TRAIN ONLY
    X = vec.transform(docs)
    svd = TruncatedSVD(n_components=EMB_DIM, random_state=0)
    svd.fit(X[tr_mask])
    Z = svd.transform(X)
    out = pd.DataFrame(Z, index=months,
                       columns=[f"news_pc{i+1}" for i in range(EMB_DIM)])
    out.index.name = "month"
    info = {"encoder": "tfidf(max_features=2000) -> TruncatedSVD",
            "vocab_fit_months": int(tr_mask.sum()),
            "explained_variance_ratio": [round(float(x), 4)
                                         for x in svd.explained_variance_ratio_]}
    return out, info


def to_panel(df: pd.DataFrame, periods: list[str], cols: list[str],
             std: bool = True) -> tuple[pd.DataFrame, dict]:
    out = df.reindex(periods)[cols].astype(float)
    n_nan = out.isna().sum()
    tr = np.array([p <= TRAIN_END for p in periods])
    scaler = {}
    if std:
        for c in cols:
            mu = float(np.nanmean(out.loc[tr, c].to_numpy()))
            sd = float(np.nanstd(out.loc[tr, c].to_numpy()))
            if not np.isfinite(sd) or sd == 0:
                raise RuntimeError(f"degenerate scaler for {c}: sd={sd}")
            out[c] = (out[c] - mu) / sd
            scaler[c] = {"mu": round(mu, 6), "sd": round(sd, 6)}
    # impute NO-COVERAGE months to the training mean, i.e. z = 0
    out = out.fillna(0.0) if std else out
    rep = {"train_end": TRAIN_END, "n_train_months": int(tr.sum()),
           "missing_before_impute": {c: int(n_nan[c]) for c in cols},
           "scaler": scaler, "imputation": "no-coverage month -> train mean (z=0)"}
    return out, rep


def main() -> int:
    d = load_headlines()
    print(f"headlines {len(d):,} over {d['month'].nunique()} months "
          f"{d['month'].min()}..{d['month'].max()}")

    # ---- coverage report --------------------------------------------------
    cov = d.groupby("month").size()
    allm = pd.Series(0, index=[m for m in sorted(cov.index)])
    print("\ncoverage by year (months with >=1 headline / 12):")
    by_year = {}
    for y in range(2004, 2025):
        ms = [m for m in cov.index if m[:4] == str(y)]
        withnews = sum(1 for m in ms if cov[m] > 0)
        by_year[y] = {"months": len(ms), "with_news": withnews,
                      "headlines": int(cov[[m for m in ms]].sum())}
        print(f"  {y}  months={len(ms):2d}  with_news={withnews:2d}  "
              f"headlines={int(cov[[m for m in ms]].sum()):5d}")

    periods = [str(p) for p in
               pd.read_csv(ROOT.parent / "stage0" / "data" / "panel_wide.csv",
                           index_col=0).index]

    # ---- scalar block -----------------------------------------------------
    sc = month_scalar(d)
    print(f"\nscalar months computed: {len(sc)}")
    SC_COLS = ["news_log_count", "news_fin_share", "news_sent_net"]

    # ---- embedding block (ST, fallback TF-IDF) ---------------------------
    try:
        emb, emb_info = month_embeddings_st(d)
    except Exception as exc:                                  # noqa: BLE001
        print(f"  sentence-transformers unavailable ({type(exc).__name__}: {exc})"
              f" -> falling back to TF-IDF")
        emb, emb_info = month_embeddings_tfidf(d)
    print(f"embedding encoder: {emb_info['encoder']}")
    print(f"  explained variance ratio {emb_info['explained_variance_ratio']} "
          f"(sum {sum(emb_info['explained_variance_ratio']):.3f})")
    EMB_COLS = [f"news_pc{i+1}" for i in range(EMB_DIM)]

    sc_z, sc_rep = to_panel(sc, periods, SC_COLS)
    emb_z, emb_rep = to_panel(emb, periods, EMB_COLS)

    wide = pd.concat([sc_z, emb_z], axis=1)
    wide.index.name = "period"
    out = DATA / "news_text_wide.csv"
    wide.to_csv(out)
    meta = {"coverage_by_year": by_year, "scalar": sc_rep, "embedding": emb_rep,
            "embedding_info": emb_info,
            "columns": SC_COLS + EMB_COLS,
            "n_rows": len(wide)}
    (DATA / "news_text_meta.json").write_text(
        json.dumps(meta, indent=2, ensure_ascii=False, default=str), encoding="utf-8")

    print(f"\nwrote {out.name}: {wide.shape[0]} rows x {wide.shape[1]} cols")
    print(wide.describe().round(3).to_string())
    nn = sum(int(v) for v in sc_rep["missing_before_impute"].values())
    print(f"\nno-coverage months imputed to train mean: "
          f"{sc_rep['missing_before_impute']['news_log_count']} of {len(periods)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
